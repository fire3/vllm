#!/usr/bin/env bash
# Pin the dependency versions currently installed in the active conda env.
#
#   conda activate vllm-dsv4-sm89
#   bash scripts/build/sm89_pin_deps.sh                        # full env lock
#   bash scripts/build/sm89_pin_deps.sh --top-level            # only requirements/*.txt packages
#   bash scripts/build/sm89_pin_deps.sh requirements/cuda.txt  # top-level from given files
#   bash scripts/build/sm89_pin_deps.sh --output /tmp/lock.txt # custom output path
#
# The default output is requirements-lock.txt at the repo root. Full-env mode
# records every installed package (editable vllm excluded); --top-level mode
# pins only packages declared in the given requirements files and fails if any
# declared package is not installed.
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
PYTHON="${CONDA_PREFIX:?run inside your conda env, e.g. \"conda activate vllm-dsv4-sm89\"}/bin/python"
OUTPUT="${REPO_ROOT}/requirements-lock.txt"
TOP_LEVEL=0
REQ_FILES=()

usage() {
  sed -n '2,13p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'
  exit "${1:-0}"
}

while [[ $# -gt 0 ]]; do
  case "$1" in
    --top-level) TOP_LEVEL=1; shift ;;
    --output) OUTPUT="${2:?--output requires a path}"; shift 2 ;;
    -h|--help) usage ;;
    --) shift; break ;;
    -*)
      echo "Unknown option: $1" >&2
      usage 2
      ;;
    *) REQ_FILES+=("$1"); shift ;;
  esac
done

if [[ "${#REQ_FILES[@]}" -gt 0 ]]; then
  TOP_LEVEL=1
fi
if [[ "${TOP_LEVEL}" -eq 1 && "${#REQ_FILES[@]}" -eq 0 ]]; then
  REQ_FILES=(requirements/common.txt requirements/cuda.txt requirements/build/cuda.txt)
fi

REQ_PATHS=()
for f in "${REQ_FILES[@]}"; do
  if [[ "$f" == /* ]]; then
    REQ_PATHS+=("$f")
  else
    REQ_PATHS+=("${REPO_ROOT}/${f}")
  fi
done

mkdir -p "$(dirname "${OUTPUT}")"

if [[ "${TOP_LEVEL}" -eq 0 ]]; then
  if command -v uv >/dev/null 2>&1; then
    uv pip freeze --python "${PYTHON}" --exclude-editable \
      | grep -vE '^vllm([ @=-]|$)' > "${OUTPUT}"
  else
    "${PYTHON}" -m pip freeze --exclude-editable \
      | grep -vE '^vllm([ @=-]|$)' > "${OUTPUT}"
  fi
else
  "${PYTHON}" - "${REQ_PATHS[@]}" <<'PY' > "${OUTPUT}"
import sys
from pathlib import Path

from importlib import metadata
from packaging.markers import UndefinedEnvironmentName, default_environment
from packaging.requirements import Requirement


def iter_requirements(files):
    seen = set()

    def walk(path):
        path = Path(path).resolve()
        if path in seen:
            return
        seen.add(path)
        for raw in path.read_text().splitlines():
            line = raw.split("#", 1)[0].strip()
            if not line or line.startswith(("--", "-e")):
                continue
            if line.startswith("-r "):
                walk(path.parent / line[3:].strip())
                continue
            req = Requirement(line)
            if req.marker is not None:
                try:
                    if not req.marker.evaluate(default_environment()):
                        continue
                except UndefinedEnvironmentName:
                    continue
            yield req

    for file in files:
        yield from walk(file)


missing = []
pinned = {}
for req in iter_requirements(sys.argv[1:]):
    try:
        version = metadata.version(req.name)
    except metadata.PackageNotFoundError:
        missing.append(req.name)
        continue
    pinned[req.name] = version

if missing:
    print("Declared but not installed:", file=sys.stderr)
    for name in sorted(set(missing)):
        print(f"  {name}", file=sys.stderr)
    sys.exit(1)

for name in sorted(pinned):
    print(f"{name}=={pinned[name]}")
PY
fi

{
  printf '# Generated by scripts/build/sm89_pin_deps.sh at %s\n' "$(date -Is)"
  printf '# Environment: %s\n' "${CONDA_PREFIX}"
  cat "${OUTPUT}"
} > "${OUTPUT}.tmp"
mv "${OUTPUT}.tmp" "${OUTPUT}"

COUNT="$(grep -cE '^[A-Za-z0-9_.-]+==' "${OUTPUT}")"
echo "Pinned ${COUNT} packages -> ${OUTPUT}"
if grep -qE '^[A-Za-z0-9_.-]+==[^ ]*\+' "${OUTPUT}"; then
  echo "Note: +<local> pins (e.g. +cu130) must be installed from their local index."
fi
